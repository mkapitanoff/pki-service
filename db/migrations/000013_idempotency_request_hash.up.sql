-- 000013_idempotency_request_hash.up.sql
--
-- Фингерпринт тела запроса для Idempotency-Key.
--
-- Проблема: раньше при повторе того же ключа сервис молча отдавал ранее
-- сохранённый ответ, даже если ТЕЛО запроса стало другим. Клиент, собравший
-- ключ из нестабильного базиса (например application_id + имена файлов),
-- получал устаревшие doc_id и хэши прошлого прогона — вместо ошибки.
--
-- Решение (канонический паттерн, как у Stripe): хранить SHA-256 сырого тела
-- запроса. При совпадении ключа сверяем фингерпринт:
--   request_hash IS NULL      → legacy-строка, реплеим как раньше;
--   request_hash = текущему   → реплей (честный ретрай той же операции);
--   request_hash ≠ текущему   → 409 IDEMPOTENCY_KEY_REUSED.
--
-- Колонка nullable: существующие строки продолжают работать, клиенты без
-- заголовка Idempotency-Key не затронуты вообще.
ALTER TABLE idempotency_keys
    ADD COLUMN request_hash TEXT;
